/**
 * Prints several conversions of the same value.
 * @param {unknown} v The value to convert
 * @returns {void}
 */
const show = (v) => console.log(JSON.stringify(v), Number(v), String(v), Boolean(v));

["42", "", "abc", 0, null, undefined].forEach(show);
console.log("1" + 2, "3" * "4", [] + {}, 1 == "1", 1 === "1");
