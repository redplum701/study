"use strict";

/** A simple counter. */
class Counter {
  count = 0;
  #secret = 42; // A private field
  static instances = 0;

  constructor() {
    Counter.instances++;
  }

  /** @returns {this} Enables method chaining */
  inc() {
    this.count++;
    return this;
  }

  get secret() {
    return this.#secret;
  }
}

console.log(new Counter().inc().inc().count); // 2
console.log(Counter.instances, new Counter().secret); // 1 42
